// Derives each semantic tool's mandatory fields from the TDEI OpenAPI spec.
//
//   pnpm gen:tool-fields            write src/intents/generated/tool-fields.generated.ts
//   pnpm check:tool-fields          exit 1 if the committed file differs from the spec
//
// Spec source: argv[2] (path or URL), else TDEI_SPEC_URL, else the default gateway spec.
import SwaggerParser from "@apidevtools/swagger-parser";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { semanticFieldNames, TOOL_SPEC_BINDINGS } from "../src/intents/tool-spec-map.js";

const DEFAULT_SPEC = "https://raw.githubusercontent.com/TaskarCenterAtUW/TDEI-ExternalAPIs/dev/tdei-api-gateway.json";
const OUT = fileURLToPath(new URL("../src/intents/generated/tool-fields.generated.ts", import.meta.url));

type Json = Record<string, unknown>;
const isObj = (v: unknown): v is Json => typeof v === "object" && v !== null && !Array.isArray(v);

function operationsById(spec: Json): Map<string, Json> {
  const out = new Map<string, Json>();
  for (const item of Object.values(isObj(spec.paths) ? spec.paths : {})) {
    if (!isObj(item)) continue;
    for (const op of Object.values(item)) {
      if (isObj(op) && typeof op.operationId === "string") out.set(op.operationId, op);
    }
  }
  return out;
}

function requiredSpecFields(op: Json): Set<string> {
  const required = new Set<string>();
  for (const p of Array.isArray(op.parameters) ? op.parameters : []) {
    if (isObj(p) && p.required === true && typeof p.name === "string") required.add(p.name);
  }
  const content = isObj(op.requestBody) && isObj(op.requestBody.content) ? op.requestBody.content : {};
  const first = Object.values(content)[0];
  const schema = isObj(first) && isObj(first.schema) ? first.schema : undefined;
  for (const name of Array.isArray(schema?.required) ? schema.required : []) {
    if (typeof name === "string") required.add(name);
  }
  return required;
}

async function main(): Promise<void> {
  const source = process.argv.slice(2).find((a) => !a.startsWith("--")) ?? process.env.TDEI_SPEC_URL ?? DEFAULT_SPEC;
  const spec = (await SwaggerParser.dereference(
    source,
    /^https?:/i.test(source) ? { resolve: { file: false } } : {},
  )) as unknown as Json;
  const ops = operationsById(spec);

  const rows: string[] = [];
  for (const [tool, binding] of Object.entries(TOOL_SPEC_BINDINGS)) {
    const perOp = binding.ops.map((id) => {
      const op = ops.get(id);
      if (!op) throw new Error(`${tool}: operation "${id}" is not in the spec`);
      return requiredSpecFields(op);
    });
    // Mandatory only if EVERY backing operation requires it.
    const common = perOp.length === 0 ? [] : [...perOp[0]!].filter((f) => perOp.every((s) => s.has(f)));
    const required = new Set<string>(binding.extraRequired ?? []);
    for (const field of common) for (const name of semanticFieldNames(field, binding)) required.add(name);
    for (const w of binding.waive ?? []) required.delete(w);
    const parts = [`required: ${JSON.stringify([...required].sort())}`];
    if (binding.oneOf) parts.push(`oneOf: ${JSON.stringify(binding.oneOf)}`);
    rows.push(`  ${tool}: { ${parts.join(", ")} },`);
  }

  const body = `// GENERATED by scripts/generate-tool-fields.ts from the TDEI OpenAPI spec. Do not edit.
// Regenerate with \`pnpm gen:tool-fields\`; \`pnpm check:tool-fields\` detects drift.
export interface ToolSpecFields {
  required: readonly string[];
  oneOf?: readonly string[];
}

export const TOOL_SPEC_FIELDS: Readonly<Record<string, ToolSpecFields>> = {
${rows.join("\n")}
};
`;
  if (process.argv.includes("--check")) {
    const current = readFileSync(OUT, "utf-8");
    if (current !== body) {
      console.error("tool-fields.generated.ts is out of date with the spec. Run: pnpm gen:tool-fields");
      process.exit(1);
    }
    console.log("tool-fields.generated.ts matches the spec.");
    return;
  }
  writeFileSync(OUT, body);
  console.log(`wrote ${rows.length} tools to ${OUT}`);
}

await main();
